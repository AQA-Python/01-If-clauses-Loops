## Задача 1. Количество грибов
#Пользователь вводит целое число — количество собранных грибов.
#Программа должна вывести сообщение вида:
#- "Мы собрали **1 гриб**"
#- "Мы собрали **2 гриба**"
#- "Мы собрали **5 грибов**"
#То есть необходимо подобрать правильную форму слова **"гриб"** в зависимости от числа.
#Если введено отрицательное число — вывести `"Input error"`.


mushrooms = int (input ("Input number"))
if mushrooms < 0: 
    print ("Input error")    

elif  11 <= mushrooms <= 14:
    print ("Мы собрали " + str(mushrooms) + " грибов")

elif mushrooms % 10  in[2,3,4]:
    print ("Мы собрали " + str(mushrooms) + " гриба")

elif mushrooms % 10  in[0,5,6,7,8,9]:
    print ("Мы собрали " + str(mushrooms) + " грибов")

elif mushrooms % 10  in[1]:
    print ("Мы собрали " + str(mushrooms) + " гриб")
